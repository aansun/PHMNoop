/// An activity's picture at `size` points, in the colour of the surrounding foreground style; its SF Symbol when it has none.
struct NunaActivityGlyph: View {
    let name: String
    var size: CGFloat = 24
    var body: some View {
        if let asset = NunaActivityIcons.asset(for: name) {
            Image(asset).renderingMode(.template).resizable().scaledToFit().frame(width: size, height: size).accessibilityHidden(true)
        } else {
            NunaGlyph(ActivitySport.symbol(for: name), pointSize: size * 0.85, weight: .regular).frame(width: size, height: size)
        }
    }
}

/// An icon given either as an SF Symbol name or as `met:<id>`, a drawn metric picture from Assets.xcassets/MetricIcons (thin line, template image,
/// so it takes the colour of the text around it). `size` is the point size of the symbol; a picture is drawn a little larger to match its weight.
struct NunaIcon: View {
    let name: String
    var size: CGFloat = 18
    var weight: Font.Weight = .regular
    var body: some View {
        if name.hasPrefix("met:") {
            Image("met-" + name.dropFirst(4)).renderingMode(.template).resizable().scaledToFit()
                .frame(width: size * 1.3, height: size * 1.3).accessibilityHidden(true)
        } else if let vital = NunaVitalGlyph(name: name, size: size * 1.15) {
            vital
        } else {
            Image(systemName: name).font(.nuna(size: size, weight: weight))
        }
    }
}
